/* Convenção BERG: identificador = AAAA-MM-slug.
   O sistema deriva automaticamente mês/ano e a pasta-base da notícia.
   Campos explícitos continuam aceitos para compatibilidade. */
(function(){
  const MESES = {
    "01":["JAN","Janeiro"],"02":["FEV","Fevereiro"],"03":["MAR","Março"],
    "04":["ABR","Abril"],"05":["MAI","Maio"],"06":["JUN","Junho"],
    "07":["JUL","Julho"],"08":["AGO","Agosto"],"09":["SET","Setembro"],
    "10":["OUT","Outubro"],"11":["NOV","Novembro"],"12":["DEZ","Dezembro"]
  };
  const db=window.BERG_NOTICIAS||{};
  Object.entries(db).forEach(([id,n])=>{
    const m=id.match(/^(\d{4})-(\d{2})-/);
    if(!m) return;
    const ano=m[1], mes=m[2], nomes=MESES[mes];
    if(nomes){
      n.data=n.data||`${nomes[0]} ${ano}`;
      n.dataLonga=n.dataLonga||`${nomes[1]} ${ano}`;
    }
    n.pasta=`noticias/${id}/`;
    if(!n.imagem) n.imagem=n.pasta+"imagem.jpg";
    /* link só é presumido quando o cadastro declarar temMateria:true */
    if(!n.link && n.temMateria===true) n.link=n.pasta+"index.html";
  });
})();
